with
ext as (
  select string_agg(format('create extension if not exists %I with schema %I;', e.extname, n.nspname), E'\n' order by e.extname) as s
  from pg_extension e join pg_namespace n on n.oid = e.extnamespace
  where e.extname <> 'plpgsql'
),
enums as (
  select string_agg(
    format('create type public.%I as enum (%s);', t.typname,
      (select string_agg(quote_literal(e.enumlabel), ', ' order by e.enumsortorder)
       from pg_enum e where e.enumtypid = t.oid)),
    E'\n' order by t.typname) as s
  from pg_type t join pg_namespace n on n.oid = t.typnamespace
  where n.nspname = 'public' and t.typtype = 'e'
),
seqs as (
  select string_agg(format('create sequence if not exists public.%I;', c.relname), E'\n' order by c.relname) as s
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind = 'S'
    and not exists (
      select 1 from pg_depend d
      where d.objid = c.oid and d.deptype = 'i'
    )
),
tables as (
  select string_agg(ddl, E'\n\n' order by relname) as s
  from (
    select c.relname,
      format('create table if not exists public.%I (\n  %s\n);', c.relname,
        (select string_agg(
           format('%I %s%s%s', a.attname, format_type(a.atttypid, a.atttypmod),
             case
               when a.attidentity = 'a' then ' generated always as identity'
               when a.attidentity = 'd' then ' generated by default as identity'
               when a.attgenerated = 's' then format(' generated always as (%s) stored', pg_get_expr(d.adbin, d.adrelid))
               when d.adbin is not null then format(' default %s', pg_get_expr(d.adbin, d.adrelid))
               else ''
             end,
             case when a.attnotnull then ' not null' else '' end),
           E',\n  ' order by a.attnum)
         from pg_attribute a
         left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
         where a.attrelid = c.oid and a.attnum > 0 and not a.attisdropped)
      ) as ddl
    from pg_class c join pg_namespace n on n.oid = c.relnamespace
    where n.nspname = 'public' and c.relkind = 'r' and c.relpersistence = 'p'
  ) t
)
select concat_ws(E'\n\n', ext.s, enums.s, seqs.s, tables.s) as schema_part_1
from ext, enums, seqs, tables;
